/** Client-side JSON fetch helper. Throws Error(message) from `{error}` bodies. */
export async function api<T = unknown>(url: string, init?: RequestInit & { json?: unknown }): Promise<T> {
  const { json, ...rest } = init ?? {};
  const res = await fetch(url, {
    ...rest,
    headers: { ...(json !== undefined ? { "content-type": "application/json" } : {}), ...rest.headers },
    body: json !== undefined ? JSON.stringify(json) : rest.body,
  });
  const text = await res.text();
  const data = text ? JSON.parse(text) : null;
  if (!res.ok) { const e = new Error(data?.error ?? `Request failed (${res.status})`) as Error & { status: number; data: unknown }; e.status = res.status; e.data = data; throw e; }
  return data as T;
}
